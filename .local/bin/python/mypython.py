# Byte conversions
def kilo(num : int):
    return num*1024
def mega(num : int):
    return num*1024*1024
def giga(num : int):
    return num*1024*1024*1024
def tera(num : int):
    return num*1024*1024*1024*1024
def hexk(num : int):
    return hex(kilo(num))
def hexm(num : int):
    return hex(mega(num))
def hexg(num : int):
    return hex(giga(num))
def hext(num : int):
    return hex(tera(num))
